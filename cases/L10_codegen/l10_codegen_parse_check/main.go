// L10: 用 text/template 生成 Go 源码文本，再交给 go/parser + go/types 做完整类型检查。
// 覆盖：正常生成、语法错误、类型错误、AST 结构断言、重复渲染确定性。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"math/rand"
	"os"
	"runtime"
	"strconv"
	"strings"
	"sync/atomic"
	"text/template"
)

var (
	failed  int32
	gcSink  [][]byte
	curSeed int64
)

func ck(ok bool, msg string) {
	if !ok {
		atomic.AddInt32(&failed, 1)
		fmt.Println("FAIL:", msg)
	}
}

func ckSeed(ok bool, msg string) {
	if !ok {
		atomic.AddInt32(&failed, 1)
		fmt.Printf("FAIL: %s (seed=%d)\n", msg, curSeed)
	}
}

func gcStress() {
	for i := 0; i < 16; i++ {
		b := make([]byte, 4096)
		b[0] = byte(i)
		gcSink = append(gcSink[:0], b)
	}
	gcSink = gcSink[:0]
	runtime.GC()
	runtime.GC()
}

func finish(name string) {
	if n := atomic.LoadInt32(&failed); n != 0 {
		fmt.Printf("FAILED %s (%d failed checks)\n", name, n)
		os.Exit(1)
	}
	fmt.Println("ALL PASS " + name)
}

type fieldSpec struct {
	Name   string
	Type   string
	Getter string
	Zero   string
}

type typeSpec struct {
	Name   string
	Fields []fieldSpec
}

type tmplData struct {
	Types    []typeSpec
	Statuses []string
}

var genTmpl = template.Must(template.New("gen").Funcs(template.FuncMap{
	"inc": func(i int) int { return i + 1 },
}).Parse(`// Code generated by l10gen. DO NOT EDIT.
package gen

{{range .Types}}
type {{.Name}} struct {
	Name string
{{- range .Fields}}
	{{.Name}} {{.Type}}
{{- end}}
}

func (x *{{.Name}}) GetName() string {
	if x != nil {
		return x.Name
	}
	return ""
}
{{$t := .}}
{{range .Fields}}
func (x *{{$t.Name}}) {{.Getter}}() {{.Type}} {
	if x != nil {
		return x.{{.Name}}
	}
	return {{.Zero}}
}
{{end}}
func (x *{{.Name}}) Init() {
	*x = {{.Name}}{}
}
{{end}}

type Status int32

const (
	StatusUnknown Status = 0
{{- range $i, $s := .Statuses}}
	Status{{$s}} Status = {{inc $i}}
{{- end}}
)

func (s Status) Valid() bool {
	switch s {
	case StatusUnknown{{range .Statuses}}, Status{{.}}{{end}}:
		return true
	}
	return false
}

type Service interface {
{{- range .Types}}
	Do{{.Name}}(*{{.Name}}) string
{{- end}}
}

type impl struct{}

{{range .Types}}
func (impl) Do{{.Name}}(x *{{.Name}}) string {
	return x.GetName()
}
{{end}}
func Dispatch(s Status, v int64) int64 {
	switch s {
{{- range $i, $s := .Statuses}}
	case Status{{$s}}:
		return v + {{$i}}
{{- end}}
	default:
		return -1
	}
}
`))

var statusNames = []string{"A", "B", "C", "D", "E", "F"}
var fieldTypes = []struct {
	Type string
	Zero string
}{
	{"string", `""`},
	{"int64", "0"},
	{"int32", "0"},
	{"bool", "false"},
	{"float64", "0"},
	{"[]byte", "nil"},
	{"[]string", "nil"},
}

func buildData(r *rand.Rand) tmplData {
	nTypes := 3 + r.Intn(3)
	d := tmplData{Statuses: append([]string(nil), statusNames...)}
	for i := 0; i < nTypes; i++ {
		t := typeSpec{Name: fmt.Sprintf("Item%d", i)}
		nFields := 4 + r.Intn(7)
		used := map[string]bool{}
		for j := 0; j < nFields; j++ {
			name := fmt.Sprintf("F%02d", j)
			for used[name] {
				name += "x"
			}
			used[name] = true
			ft := fieldTypes[r.Intn(len(fieldTypes))]
			t.Fields = append(t.Fields, fieldSpec{
				Name:   name,
				Type:   ft.Type,
				Getter: "Get" + name,
				Zero:   ft.Zero,
			})
		}
		d.Types = append(d.Types, t)
	}
	return d
}

func render(d tmplData) (string, error) {
	var buf bytes.Buffer
	if err := genTmpl.Execute(&buf, d); err != nil {
		return "", err
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("format: %w", err)
	}
	return string(out), nil
}

func parseFile(src string) (*token.FileSet, *ast.File, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "gen.go", src, parser.ParseComments)
	return fset, f, err
}

func typeCheck(src string) (*types.Package, *types.Info, error) {
	fset, f, err := parseFile(src)
	if err != nil {
		return nil, nil, err
	}
	info := &types.Info{
		Defs: map[*ast.Ident]types.Object{},
		Uses: map[*ast.Ident]types.Object{},
	}
	conf := types.Config{} // 生成源码不 import 任何包，无需 Importer。
	pkg, err := conf.Check("gen", fset, []*ast.File{f}, info)
	return pkg, info, err
}

func methodNames(pkg *types.Package, typeName string) []string {
	obj := pkg.Scope().Lookup(typeName)
	if obj == nil {
		return nil
	}
	named, ok := obj.Type().(*types.Named)
	if !ok {
		return nil
	}
	ms := types.NewMethodSet(types.NewPointer(named))
	out := make([]string, 0, ms.Len())
	for i := 0; i < ms.Len(); i++ {
		out = append(out, ms.At(i).Obj().Name())
	}
	return out
}

func hasMethod(pkg *types.Package, typeName, method string) bool {
	for _, m := range methodNames(pkg, typeName) {
		if m == method {
			return true
		}
	}
	return false
}

func main() {
	curSeed = 1
	if s := os.Getenv("UAF_SEED"); s != "" {
		if v, err := strconv.ParseInt(s, 10, 64); err == nil {
			curSeed = v
		}
	}

	r := rand.New(rand.NewSource(curSeed))
	data := buildData(r)

	// 1. 正常生成：格式合法、重复渲染逐字节一致。
	src1, err := render(data)
	ck(err == nil, "template render")
	src2, err := render(data)
	ck(err == nil && src1 == src2, "render deterministic")
	ck(strings.Contains(src1, "package gen"), "package header")
	ck(strings.HasPrefix(src1, "// Code generated by l10gen. DO NOT EDIT."), "generated marker")

	// 2. go/parser 解析成功，AST 结构符合预期。
	_, f, err := parseFile(src1)
	ck(err == nil, "parser accepts generated source")
	if err == nil {
		ck(f.Name.Name == "gen", "AST package name")
		nStruct, nFunc := 0, 0
		ast.Inspect(f, func(n ast.Node) bool {
			switch n.(type) {
			case *ast.StructType:
				nStruct++
			case *ast.FuncDecl:
				nFunc++
			}
			return true
		})
		// Item 类型各一个 struct，另有 template 里的 impl struct。
		ck(nStruct == len(data.Types)+1, "AST struct count")
		// 每类型：GetName + 每字段 getter + Init + impl 方法；外加 Valid + Dispatch。
		wantFuncs := 2
		for _, t := range data.Types {
			wantFuncs += len(t.Fields) + 3
		}
		ck(nFunc == wantFuncs, fmt.Sprintf("AST func count got %d want %d", nFunc, wantFuncs))
		ck(len(f.Decls) > len(data.Types)+2, "AST declaration count")
	}

	// 3. go/types 全量类型检查 + 作用域/方法集断言。
	pkg, info, err := typeCheck(src1)
	ck(err == nil, "types.Check passes")
	if err == nil {
		ck(pkg.Name() == "gen", "types package name")
		ck(len(info.Defs) > 0, "types info defs populated")
		for _, t := range data.Types {
			obj := pkg.Scope().Lookup(t.Name)
			ck(obj != nil, "type scope "+t.Name)
			if obj == nil {
				continue
			}
			st, ok := obj.Type().Underlying().(*types.Struct)
			ck(ok && st.NumFields() == len(t.Fields)+1, "struct fields "+t.Name)
			ck(hasMethod(pkg, t.Name, "GetName"), "method GetName "+t.Name)
			ck(hasMethod(pkg, t.Name, "Init"), "method Init "+t.Name)
			for _, fs := range t.Fields {
				ck(hasMethod(pkg, t.Name, fs.Getter), "getter "+t.Name+"."+fs.Getter)
			}
		}
		ck(pkg.Scope().Lookup("StatusUnknown") != nil, "enum zero constant")
		for i, s := range data.Statuses {
			cobj, ok := pkg.Scope().Lookup("Status" + s).(*types.Const)
			ck(ok && cobj.Val().String() == strconv.Itoa(i+1), "enum constant Status"+s)
		}
		ifaceObj := pkg.Scope().Lookup("Service")
		ck(ifaceObj != nil, "Service interface present")
		if ifaceObj != nil {
			iface, ok := ifaceObj.Type().Underlying().(*types.Interface)
			ck(ok && iface.NumMethods() == len(data.Types), "Service method count")
		}
		ck(pkg.Scope().Lookup("Dispatch") != nil, "Dispatch function present")
	}

	// 4. 语法错误必须被 parser 拒绝。
	if _, _, err := parseFile(src1 + "\nfunc broken( {\n"); err == nil {
		ck(false, "parser must reject syntax error")
	}
	// 5. 类型错误必须被 types 检查拒绝。
	if _, _, err := typeCheck(src1 + "\nvar injectedTypeError int = \"str\"\n"); err == nil {
		ck(false, "types must reject type error")
	}
	// 6. 未定义类型也必须失败。
	if _, _, err := typeCheck(src1 + "\nvar injectedUndefined MissingType\n"); err == nil {
		ck(false, "types must reject undefined type")
	}

	// 7. GC 后重新渲染/检查同一种子输入，输出仍一致。
	gcSink = append(gcSink, []byte(src1))
	gcStress()
	src3, err := render(data)
	ck(err == nil && src3 == src1, "render stable after GC")
	if _, _, err := typeCheck(src3); err != nil {
		ckSeed(false, "type check after GC")
	}

	// 8. 不同种子生成不同规模，全部通过类型检查。
	for k := 1; k <= 3; k++ {
		d := buildData(rand.New(rand.NewSource(curSeed + int64(k)*97)))
		s, err := render(d)
		if err != nil {
			ckSeed(false, fmt.Sprintf("seed variant %d render", k))
			continue
		}
		if _, _, err := typeCheck(s); err != nil {
			ckSeed(false, fmt.Sprintf("seed variant %d typecheck: %v", k, err))
		}
		var gotBytes []byte
		if _, f, err := parseFile(s); err == nil {
			ast.Inspect(f, func(n ast.Node) bool {
				if fd, ok := n.(*ast.FuncDecl); ok && fd.Recv != nil {
					gotBytes = append(gotBytes, 1)
				}
				return true
			})
		}
		if len(gotBytes) < len(d.Types) {
			ckSeed(false, fmt.Sprintf("seed variant %d methods", k))
		}
	}

	finish("l10_codegen_parse_check")
}
