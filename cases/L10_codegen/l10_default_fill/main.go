type Profile struct {
	ID         *int64
	Name       *string
	Score      *float64
	Active     *bool
	Kind       *int32
	Blob       []byte
	Tags       []string
	Attrs      map[string]int64
	Child      *Child
	EmptyMap   map[string]int64
	EmptySlice []string
}

type Child struct {
	Name  *string
	Depth *int32
	Leaf  *Leaf
}

type Leaf struct {
	Value *string
}

func fillWith(v any, typeName string, t *defaultsTable) error {
	rv := reflect.ValueOf(v)
	if rv.Kind() != reflect.Ptr || rv.IsNil() {
		return fmt.Errorf("fill: expected non-nil pointer to %s", typeName)
	}
	st := rv.Elem()
	if st.Kind() != reflect.Struct {
		return fmt.Errorf("fill: expected struct, got %s", st.Kind())
	}
	if got := st.Type().Name(); got != typeName {
		return fmt.Errorf("fill: type mismatch: have %s, want %s", got, typeName)
	}
	for _, fd := range t.Fields[typeName] {
		fv := st.FieldByName(fd.Name)
		if !fv.IsValid() {
			return fmt.Errorf("fill: %s has no field %s", typeName, fd.Name)
		}
		if fd.Def == nil {
			continue
		}
		switch fd.Kind {
		case "int", "float", "bool", "string":
			if fv.Kind() != reflect.Ptr || fv.Type().Elem().Kind() != reflect.Int64 && fv.Type().Elem().Kind() != reflect.Int32 &&
				fv.Type().Elem().Kind() != reflect.Float64 && fv.Type().Elem().Kind() != reflect.Bool &&
				fv.Type().Elem().Kind() != reflect.String {
				return fmt.Errorf("fill: %s.%s kind mismatch", typeName, fd.Name)
			}
			if !fv.IsNil() {
				continue // 显式设置（含零值）优先
			}
			p := reflect.New(fv.Type().Elem())
			switch fd.Kind {
			case "int":
				p.Elem().SetInt(fd.Def.I)
			case "float":
				p.Elem().SetFloat(fd.Def.F)
			case "bool":
				p.Elem().SetBool(fd.Def.B)
			case "string":
				p.Elem().SetString(fd.Def.S)
			}
			fv.Set(p)
		case "bytes":
			if fv.Kind() != reflect.Slice || fv.Type().Elem().Kind() != reflect.Uint8 {
				return fmt.Errorf("fill: %s.%s not []byte", typeName, fd.Name)
			}
			if fv.IsNil() {
				b := make([]byte, len(fd.Def.Bytes))
				copy(b, fd.Def.Bytes)
				fv.SetBytes(b)
			}
		case "strings":
			if fv.Kind() != reflect.Slice || fv.Type().Elem().Kind() != reflect.String {
				return fmt.Errorf("fill: %s.%s not []string", typeName, fd.Name)
			}
			if fv.IsNil() {
				s := append([]string{}, fd.Def.Strs...)
				fv.Set(reflect.ValueOf(s))
			}
		case "intmap":
			if fv.Kind() != reflect.Map || fv.Type().Key().Kind() != reflect.String || fv.Type().Elem().Kind() != reflect.Int64 {
				return fmt.Errorf("fill: %s.%s not map[string]int64", typeName, fd.Name)
			}
			if fv.IsNil() {
				m := make(map[string]int64, len(fd.Def.Map))
				for k, x := range fd.Def.Map {
					m[k] = x
				}
				fv.Set(reflect.ValueOf(m))
			}
		}
	}
	return nil
}

var defaults = func() *defaultsTable {
	t, err := buildDefaults(genSrc)
	if err != nil {
		panic(err)
	}
	return t
}()

func (m *Profile) FillDefaults() {
	if m == nil {
		return
	}
	_ = fillWith(m, "Profile", defaults)
	if m.Child != nil {
		_ = fillWith(m.Child, "Child", defaults)
		if m.Child.Leaf != nil {
			_ = fillWith(m.Child.Leaf, "Leaf", defaults)
		}
	}
}

func NewProfile() *Profile {
	m := &Profile{Child: &Child{Leaf: &Leaf{}}}
	m.FillDefaults()
	return m
}

func ptrStr[T any](p *T) string {
	if p == nil {
		return "<nil>"
	}
	return fmt.Sprint(*p)
}

func dumpProfile(m *Profile) string {
	if m == nil {
		return "<nil>"
	}
	s := fmt.Sprintf("id=%s name=%s score=%s active=%s kind=%s blob=",
		ptrStr(m.ID), ptrStr(m.Name), ptrStr(m.Score), ptrStr(m.Active), ptrStr(m.Kind))
	if m.Blob == nil {
		s += "<nil>"
	} else {
		s += fmt.Sprintf("%x", m.Blob)
	}
	s += ";tags="
	if m.Tags == nil {
		s += "<nil>"
	} else {
		s += fmt.Sprint(m.Tags)
	}
	s += ";attrs="
	if m.Attrs == nil {
		s += "<nil>"
	} else {
		keys := make([]string, 0, len(m.Attrs))
		for k := range m.Attrs {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			s += fmt.Sprintf("%s:%d,", k, m.Attrs[k])
		}
	}
	s += ";emptyMap="
	if m.EmptyMap == nil {
		s += "<nil>"
	} else {
		keys := make([]string, 0, len(m.EmptyMap))
		for k := range m.EmptyMap {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			s += fmt.Sprintf("%s:%d,", k, m.EmptyMap[k])
		}
	}
	s += ";emptySlice="
	if m.EmptySlice == nil {
		s += "<nil>"
	} else {
		s += fmt.Sprint(m.EmptySlice)
	}
	s += ";child="
	if m.Child == nil {
		s += "<nil>"
	} else {
		s += fmt.Sprintf("name=%s depth=%s leaf=", ptrStr(m.Child.Name), ptrStr(m.Child.Depth))
		if m.Child.Leaf == nil {
			s += "<nil>"
		} else {
			s += fmt.Sprintf("value=%s", ptrStr(m.Child.Leaf.Value))
		}
	}
	return s
}

func copyProfile(m *Profile) *Profile {
	if m == nil {
		return nil
	}
	out := &Profile{}
	cpI := func(p *int64) *int64 {
		if p == nil {
			return nil
		}
		v := *p
		return &v
	}
	cpS := func(p *string) *string {
		if p == nil {
			return nil
		}
		v := *p
		return &v
	}
	cpF := func(p *float64) *float64 {
		if p == nil {
			return nil
		}
		v := *p
		return &v
	}
	cpB := func(p *bool) *bool {
		if p == nil {
			return nil
		}
		v := *p
		return &v
	}
	cpI32 := func(p *int32) *int32 {
		if p == nil {
			return nil
		}
		v := *p
		return &v
	}
	out.ID, out.Name, out.Score, out.Active, out.Kind = cpI(m.ID), cpS(m.Name), cpF(m.Score), cpB(m.Active), cpI32(m.Kind)
	if m.Blob != nil {
		out.Blob = append([]byte{}, m.Blob...)
	}
	if m.Tags != nil {
		out.Tags = append([]string{}, m.Tags...)
	}
	if m.Attrs != nil {
		out.Attrs = map[string]int64{}
		for k, v := range m.Attrs {
			out.Attrs[k] = v
		}
	}
	if m.EmptyMap != nil {
		out.EmptyMap = map[string]int64{}
		for k, v := range m.EmptyMap {
			out.EmptyMap[k] = v
		}
	}
	if m.EmptySlice != nil {
		out.EmptySlice = append([]string{}, m.EmptySlice...)
	}
	if m.Child != nil {
		out.Child = &Child{Name: cpS(m.Child.Name), Depth: cpI32(m.Child.Depth)}
		if m.Child.Leaf != nil {
			out.Child.Leaf = &Leaf{Value: cpS(m.Child.Leaf.Value)}
		}
	}
	return out
}

func modelFill(m *Profile) *Profile {
	if m == nil {
		return nil
	}
	out := copyProfile(m)
	if out.ID == nil {
		out.ID = func() *int64 { v := int64(7); return &v }()
	}
	if out.Name == nil {
		out.Name = func() *string { v := "anonymous"; return &v }()
	}
	if out.Score == nil {
		out.Score = func() *float64 { v := 1.5; return &v }()
	}
	if out.Active == nil {
		out.Active = func() *bool { v := true; return &v }()
	}
	if out.Kind == nil {
		out.Kind = func() *int32 { v := int32(2); return &v }()
	}
	if out.Blob == nil {
		out.Blob = []byte{1, 2}
	}
	if out.Tags == nil {
		out.Tags = []string{"a", "b", "c"}
	}
	if out.Attrs == nil {
		out.Attrs = map[string]int64{"x": 1, "y": 2}
	}
	if out.Child != nil {
		if out.Child.Name == nil {
			out.Child.Name = func() *string { v := "child"; return &v }()
		}
		if out.Child.Depth == nil {
			out.Child.Depth = func() *int32 { v := int32(1); return &v }()
		}
		if out.Child.Leaf != nil && out.Child.Leaf.Value == nil {
			out.Child.Leaf.Value = func() *string { v := "leaf"; return &v }()
		}
	}
	return out
}

func randProfile(r *rand.Rand) *Profile {
	m := &Profile{}
	optI := func() *int64 { v := int64(r.Intn(7) - 3); return &v }
	optS := func() *string { v := []string{"", "x", "id"}[r.Intn(3)]; return &v }
	optF := func() *float64 { v := []float64{0, 1.5, -2}[r.Intn(3)]; return &v }
	optB := func() *bool { v := r.Intn(2) == 0; return &v }
	optI32 := func() *int32 { v := int32(r.Intn(5) - 2); return &v }
	if r.Intn(2) == 0 {
		m.ID = optI()
	}
	if r.Intn(2) == 0 {
		m.Name = optS()
	}
	if r.Intn(2) == 0 {
		m.Score = optF()
	}
	if r.Intn(2) == 0 {
		m.Active = optB()
	}
	if r.Intn(2) == 0 {
		m.Kind = optI32()
	}
	switch r.Intn(3) {
	case 1:
		m.Blob = []byte{}
	case 2:
		m.Blob = []byte{byte(r.Intn(256))}
	}
	switch r.Intn(3) {
	case 1:
		m.Tags = []string{}
	case 2:
		m.Tags = []string{"t"}
	}
	switch r.Intn(3) {
	case 1:
		m.Attrs = map[string]int64{}
	case 2:
		m.Attrs = map[string]int64{"k": int64(r.Intn(10))}
	}
	switch r.Intn(3) {
	case 1:
		m.EmptyMap = map[string]int64{}
	case 2:
		m.EmptyMap = map[string]int64{"e": 1}
	}
	switch r.Intn(3) {
	case 1:
		m.EmptySlice = []string{}
	case 2:
		m.EmptySlice = []string{"e"}
	}
	switch r.Intn(3) {
	case 1:
		m.Child = &Child{}
	case 2:
		m.Child = &Child{Name: optS(), Depth: optI32()}
		if r.Intn(2) == 0 {
			m.Child.Leaf = &Leaf{}
			if r.Intn(2) == 0 {
				m.Child.Leaf.Value = optS()
			}
		}
	}
	return m
}

func main() {
	curSeed = 1
	if s := os.Getenv("UAF_SEED"); s != "" {
		if v, err := strconv.ParseInt(s, 10, 64); err == nil {
			curSeed = v
		}
	}

	// 1. AST 表结构与默认值解析。
	t, err := buildDefaults(genSrc)
	ck(err == nil, "generated source parses")
	if err != nil {
		finish("l10_default_fill")
		return
	}
	ck(fmt.Sprint(t.Order) == "[Profile Child Leaf]", "type declaration order")
	ck(len(t.Fields["Profile"]) == 11 && len(t.Fields["Child"]) == 3 && len(t.Fields["Leaf"]) == 1,
		"field counts from AST")
	tagged := 0
	for _, fd := range t.Fields["Profile"] {
		if fd.Def != nil {
			tagged++
		}
	}
	ck(tagged == 8, "tagged default count")
	byName := make(map[string]fieldDefault)
	for _, fd := range t.Fields["Profile"] {
		byName[fd.Name] = fd
	}
	ck(byName["ID"].Def.I == 7 && byName["ID"].Kind == "int", "int default parsed")
	ck(byName["Name"].Def.S == "anonymous", "string default parsed")
	ck(byName["Score"].Def.F == 1.5, "float default parsed")
	ck(byName["Active"].Def.B, "bool default parsed")
	ck(byName["Kind"].Def.I == 2 && byName["Kind"].Raw == "2", "int32 default parsed")
	ck(fmt.Sprintf("%x", byName["Blob"].Def.Bytes) == "0102", "bytes default parsed")
	ck(fmt.Sprint(byName["Tags"].Def.Strs) == "[a b c]", "string slice default parsed")
	ck(byName["Attrs"].Def.Map["x"] == 1 && byName["Attrs"].Def.Map["y"] == 2, "map default parsed")
	ck(byName["Child"].Kind == "message" && byName["Child"].Def == nil, "message pointer has no default")
	dump1 := t.dump()
	ck(strings.HasPrefix(dump1, "Profile:ID/int;raw=7;Name/string;raw=anonymous;Score/float;"), "table dump order")
	ck(t.dump() == dump1, "table dump deterministic")

	// 2. 非法的生成源码/默认值被拒绝。
	if _, err := buildDefaults("package model\ntype X struct {"); err == nil {
		ck(false, "syntax error accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "type Leaf struct {", "type Profile struct {", 1)); err == nil {
		ck(false, "duplicate type accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "Value *string `default:\"leaf\"`", "Value *string `default:\"leaf\"`\n\tValue int", 1)); err == nil {
		ck(false, "duplicate field accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"7\"`", "`default:\"abc\"`", 1)); err == nil {
		ck(false, "bad int default accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"1.5\"`", "`default:\"x\"`", 1)); err == nil {
		ck(false, "bad float default accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"true\"`", "`default:\"maybe\"`", 1)); err == nil {
		ck(false, "bad bool default accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"0102\"`", "`default:\"zz\"`", 1)); err == nil {
		ck(false, "bad bytes default accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"x=1,y=2\"`", "`default:\"x\"`", 1)); err == nil {
		ck(false, "bad map default accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "`default:\"a,b,c\"`", "`default:\"a,,c\"`", 1)); err == nil {
		ck(false, "empty string-slice element accepted")
	}
	if _, err := buildDefaults(strings.Replace(genSrc, "Child      *Child", "Child      *Child `default:\"x\"`", 1)); err == nil {
		ck(false, "default on message pointer accepted")
	}

	// 3. 零值填充：标量/容器默认值；message 指针与无 tag 容器保持 nil。
	z := &Profile{}
	z.FillDefaults()
	ck(z.ID != nil && *z.ID == 7 && z.Name != nil && *z.Name == "anonymous", "zero fill pointers")
	ck(z.Score != nil && *z.Score == 1.5 && z.Active != nil && *z.Active && z.Kind != nil && *z.Kind == 2,
		"zero fill scalar defaults")
	ck(fmt.Sprintf("%x", z.Blob) == "0102", "zero fill bytes")
	ck(fmt.Sprint(z.Tags) == "[a b c]", "zero fill string slice")
	ck(len(z.Attrs) == 2 && z.Attrs["x"] == 1 && z.Attrs["y"] == 2, "zero fill map")
	ck(z.Child == nil && z.EmptyMap == nil && z.EmptySlice == nil, "no defaults leaves nested/nil containers")

	// 4. NewProfile 递归分配并填充嵌套消息。
	np := NewProfile()
	ck(np.Child != nil && np.Child.Leaf != nil, "NewProfile allocates nested messages")
	ck(np.Child.Name != nil && *np.Child.Name == "child" && np.Child.Depth != nil && *np.Child.Depth == 1,
		"nested child defaults")
	ck(np.Child.Leaf.Value != nil && *np.Child.Leaf.Value == "leaf", "nested leaf default")
	ck(dumpProfile(np) == dumpProfile(func() *Profile { x := &Profile{Child: &Child{Leaf: &Leaf{}}}; x.FillDefaults(); return x }()),
		"FillDefaults equals NewProfile on constructed skeleton")

	// 5. 显式值/显式零值优先；非 nil 空容器不被覆盖。
	ex := NewProfile()
	zeroI := int64(0)
	zeroS := ""
	zeroB := false
	zeroI32 := int32(0)
	ex.ID = &zeroI
	ex.Name = &zeroS
	ex.Active = &zeroB
	ex.Kind = &zeroI32
	ex.Blob = []byte{}
	ex.Tags = []string{}
	ex.Attrs = map[string]int64{}
	ex.EmptyMap = map[string]int64{}
	ex.EmptySlice = []string{}
	ex.Child.Name = &zeroS
	ex.Child.Leaf = nil
	ex.FillDefaults()
	ck(ex.ID != nil && *ex.ID == 0 && *ex.Name == "" && !*ex.Active && *ex.Kind == 0,
		"explicit zero pointers preserved")
	ck(ex.Blob != nil && len(ex.Blob) == 0 && ex.Tags != nil && len(ex.Tags) == 0 && ex.Attrs != nil && len(ex.Attrs) == 0,
		"explicit empty containers preserved")
	ck(ex.Child != nil && ex.Child.Name != nil && *ex.Child.Name == "" && ex.Child.Depth != nil && *ex.Child.Depth == 1,
		"explicit child zero name preserved, depth default filled")
	ck(ex.Child.Leaf == nil, "nil leaf not allocated by FillDefaults")
	ck(ex.EmptyMap != nil && len(ex.EmptyMap) == 0 && ex.EmptySlice != nil && len(ex.EmptySlice) == 0,
		"untagged empty containers preserved")

	// 6. 幂等与表/类型不匹配。
	before := dumpProfile(z)
	z.FillDefaults()
	ck(dumpProfile(z) == before, "FillDefaults idempotent")
	if err := fillWith(z, "Child", t); err == nil {
		ck(false, "type mismatch accepted")
	}
	if err := fillWith(nil, "Profile", t); err == nil {
		ck(false, "nil fill target accepted")
	}
	var nilProfile *Profile
	nilProfile.FillDefaults()
	ck(true, "nil receiver FillDefaults safe")

	// 7. GC：默认值指针/切片/map/嵌套消息在 GC 后仍可读。
	keep := NewProfile()
	idView := keep.ID
	nameView := keep.Name
	blobView := keep.Blob
	attrView := keep.Attrs
	leafView := keep.Child.Leaf
	wantKeep := dumpProfile(keep)
	gcSink = append(gcSink, blobView, []byte(*nameView))
	gcStress()
	ck(dumpProfile(keep) == wantKeep, "filled profile survives GC")
	ck(idView != nil && *idView == 7 && *nameView == "anonymous", "default scalar pointers survive GC")
	ck(len(blobView) == 2 && blobView[1] == 2 && attrView["y"] == 2, "default containers survive GC")
	ck(leafView.Value != nil && *leafView.Value == "leaf", "nested default survives GC")
	ticks := t.dump()
	gcStress()
	ck(t.dump() == ticks && dump1 == ticks, "AST default table stable across GC")

	// 8. UAF_SEED 随机 presence 组合：与直接赋值模型对账。
	r := rand.New(rand.NewSource(curSeed))
	for i := 0; i < 240; i++ {
		m := randProfile(r)
		orig := copyProfile(m)
		want := modelFill(orig)
		m.FillDefaults()
		ckSeed(dumpProfile(m) == dumpProfile(want), fmt.Sprintf("round %d fill mismatch got=%s want=%s",
			i, dumpProfile(m), dumpProfile(want)))
		// 二次填充幂等。
		snap := dumpProfile(m)
		m.FillDefaults()
		ckSeed(dumpProfile(m) == snap, fmt.Sprintf("round %d second fill changed", i))
		if i%31 == 0 {
			gcStress()
			ckSeed(dumpProfile(m) == snap, fmt.Sprintf("round %d fill after GC", i))
		}
	}

	finish("l10_default_fill")
}
