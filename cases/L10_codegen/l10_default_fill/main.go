// ---- AST 默认值表 ----

type defVal struct {
	I     int64
	F     float64
	B     bool
	S     string
	Bytes []byte
	Strs  []string
	Map   map[string]int64
}

type fieldDefault struct {
	Type string
	Name string
	Kind string
	Raw  string
	Def  *defVal
}

type defaultsTable struct {
	Order  []string
	Fields map[string][]fieldDefault
}

func parseDefault(kind, raw, typeStr string) (*defVal, error) {
	switch kind {
	case "int":
		bits := 64
		if typeStr == "*int32" {
			bits = 32
		}
		v, err := strconv.ParseInt(raw, 10, bits)
		if err != nil {
			return nil, fmt.Errorf("default %q is not an int for %s", raw, typeStr)
		}
		return &defVal{I: v}, nil
	case "float":
		v, err := strconv.ParseFloat(raw, 64)
		if err != nil {
			return nil, fmt.Errorf("default %q is not a float", raw)
		}
		return &defVal{F: v}, nil
	case "bool":
		v, err := strconv.ParseBool(raw)
		if err != nil {
			return nil, fmt.Errorf("default %q is not a bool", raw)
		}
		return &defVal{B: v}, nil
	case "string":
		return &defVal{S: raw}, nil
	case "bytes":
		b, err := hex.DecodeString(raw)
		if err != nil {
			return nil, fmt.Errorf("default %q is not hex", raw)
		}
		if b == nil {
			b = []byte{}
		}
		return &defVal{Bytes: b}, nil
	case "strings":
		if raw == "" {
			return &defVal{Strs: []string{}}, nil
		}
		parts := strings.Split(raw, ",")
		for _, p := range parts {
			if p == "" {
				return nil, fmt.Errorf("default %q has empty element", raw)
			}
		}
		return &defVal{Strs: parts}, nil
	case "intmap":
		m := make(map[string]int64)
		if raw == "" {
			return &defVal{Map: m}, nil
		}
		for _, pair := range strings.Split(raw, ",") {
			kv := strings.SplitN(pair, "=", 2)
			if len(kv) != 2 || kv[0] == "" {
				return nil, fmt.Errorf("default %q has bad pair %q", raw, pair)
			}
			v, err := strconv.ParseInt(kv[1], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("default %q has bad value", raw)
			}
			if _, dup := m[kv[0]]; dup {
				return nil, fmt.Errorf("default %q has duplicate key %q", raw, kv[0])
			}
			m[kv[0]] = v
		}
		return &defVal{Map: m}, nil
	default:
		return nil, fmt.Errorf("unsupported default kind %s", kind)
	}
}

func classify(typeStr string) string {
	switch typeStr {
	case "*int64", "*int32":
		return "int"
	case "*float64":
		return "float"
	case "*bool":
		return "bool"
	case "*string":
		return "string"
	case "[]byte":
		return "bytes"
	case "[]string":
		return "strings"
	case "map[string]int64":
		return "intmap"
	}
	if strings.HasPrefix(typeStr, "*") {
		return "message"
	}
	if strings.HasPrefix(typeStr, "[]") {
		return "slice"
	}
	if strings.HasPrefix(typeStr, "map[") {
		return "map"
	}
	return "other"
}

func buildDefaults(src string) (*defaultsTable, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "gen_defaults.go", src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse generated source: %w", err)
	}
	t := &defaultsTable{Fields: make(map[string][]fieldDefault)}
	seenTypes := make(map[string]bool)
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts := spec.(*ast.TypeSpec)
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}
			name := ts.Name.Name
			if seenTypes[name] {
				return nil, fmt.Errorf("duplicate type %q", name)
			}
			seenTypes[name] = true
			t.Order = append(t.Order, name)
			seenFields := make(map[string]bool)
			for _, fld := range st.Fields.List {
				typeStr := types.ExprString(fld.Type)
				kind := classify(typeStr)
				tag := ""
				hasTag := false
				if fld.Tag != nil {
					unq, err := strconv.Unquote(fld.Tag.Value)
					if err != nil {
						return nil, fmt.Errorf("bad tag for %s: %w", name, err)
					}
					tag = reflect.StructTag(unq).Get("default")
					_, hasTag = reflect.StructTag(unq).Lookup("default")
				}
				for _, nm := range fld.Names {
					fn := nm.Name
					if seenFields[fn] {
						return nil, fmt.Errorf("duplicate field %s.%s", name, fn)
					}
					seenFields[fn] = true
					fd := fieldDefault{Type: name, Name: fn, Kind: kind}
					if hasTag {
						if kind == "message" || kind == "slice" || kind == "map" || kind == "other" {
							return nil, fmt.Errorf("field %s.%s: unsupported default on %s", name, fn, typeStr)
						}
						dv, err := parseDefault(kind, tag, typeStr)
						if err != nil {
							return nil, fmt.Errorf("field %s.%s: %w", name, fn, err)
						}
						fd.Raw, fd.Def = tag, dv
					}
					t.Fields[name] = append(t.Fields[name], fd)
				}
			}
		}
	}
	if len(t.Order) == 0 {
		return nil, fmt.Errorf("no struct types in generated source")
	}
	return t, nil
}

func (t *defaultsTable) dump() string {
	var b strings.Builder
	for _, typ := range t.Order {
		b.WriteString(typ)
		b.WriteByte(':')
		for _, fd := range t.Fields[typ] {
			fmt.Fprintf(&b, "%s/%s;", fd.Name, fd.Kind)
			if fd.Def != nil {
				fmt.Fprintf(&b, "raw=%s;", fd.Raw)
			}
		}
		b.WriteByte('\n')
	}
	return b.String()
}

