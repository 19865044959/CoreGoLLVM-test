// L10: 模板生成源码 + go/format/go/parser 校验：渲染确定、gofmt 幂等、
// AST 计数/注释/directive/struct tag/方法接收者校验，GC 后 AST 与源码仍一致。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"math/rand"
	"os"
	"runtime"
	"strconv"
	"strings"
	"sync/atomic"
	"text/template"
)

var (
	failed  int32
	gcSink  [][]byte
	curSeed int64
)

func ck(ok bool, msg string) {
	if !ok {
		atomic.AddInt32(&failed, 1)
		fmt.Println("FAIL:", msg)
	}
}

func ckSeed(ok bool, msg string) {
	if !ok {
		atomic.AddInt32(&failed, 1)
		fmt.Printf("FAIL: %s (seed=%d)\n", msg, curSeed)
	}
}

func gcStress() {
	for i := 0; i < 16; i++ {
		b := make([]byte, 4096)
		b[0] = byte(i)
		gcSink = append(gcSink[:0], b)
	}
	gcSink = gcSink[:0]
	runtime.GC()
	runtime.GC()
}

func finish(name string) {
	if n := atomic.LoadInt32(&failed); n != 0 {
		fmt.Printf("FAILED %s (%d failed checks)\n", name, n)
		os.Exit(1)
	}
	fmt.Println("ALL PASS " + name)
}

type genField struct {
	Name string
	Type string
	JSON string
}

type genType struct {
	Name   string
	Weight int
	Fields []genField
}

const tmplSrc = `// Code generated by l10gen. DO NOT EDIT.
//go:generate go run ./gen

package main

{{range $i, $t := .}}
// {{$t.Name}} is generated type number {{$i}}.
type {{$t.Name}} struct {
{{- range $f := $t.Fields}}
	{{$f.Name}} {{$f.Type}} {{tag $f.JSON}}
{{- end}}
}

// GetWeight returns the generated weight for {{$t.Name}}.
func (x *{{$t.Name}}) GetWeight() int { return {{$t.Weight}} }

{{end}}
`

var genTmpl = template.Must(template.New("gen").Funcs(template.FuncMap{
	"tag": func(j string) string { return "`json:\"" + j + "\"`" },
}).Parse(tmplSrc))

func render(types []genType) ([]byte, error) {
	var buf bytes.Buffer
	if err := genTmpl.Execute(&buf, types); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

var fieldTypes = []string{"int64", "string", "[]byte", "float64", "bool", "map[string]int64"}

func makeConfig(r *rand.Rand, n int) []genType {
	types := make([]genType, n)
	for i := 0; i < n; i++ {
		nf := 1 + r.Intn(6)
		fields := make([]genField, nf)
		for j := 0; j < nf; j++ {
			fields[j] = genField{
				Name: fmt.Sprintf("F%02d", j),
				Type: fieldTypes[(i+j)%len(fieldTypes)],
				JSON: fmt.Sprintf("f_%02d_%02d", i, j),
			}
		}
		types[i] = genType{
			Name:   fmt.Sprintf("GenT%02d", i),
			Weight: 100 + i*7,
			Fields: fields,
		}
	}
	return types
}

type parsedGen struct {
	src      []byte
	fset     *token.FileSet
	file     *ast.File
	typeCnt  int
	funcCnt  int
	fieldCnt []int
}

func parseCheck(src []byte, cfg []genType) (*parsedGen, bool) {
	ok := true
	formatted, err := format.Source(src)
	if err != nil {
		ck(false, "format.Source")
		return nil, false
	}
	again, err := format.Source(formatted)
	if err != nil {
		ck(false, "format.Source idempotent")
		return nil, false
	}
	if !bytes.Equal(formatted, again) {
		ck(false, "gofmt is idempotent")
		ok = false
	}
	if len(formatted) == 0 || formatted[len(formatted)-1] != '\n' {
		ck(false, "formatted source ends with newline")
		ok = false
	}
	for _, line := range bytes.Split(formatted, []byte("\n")) {
		if len(line) > 0 && (line[len(line)-1] == ' ' || line[len(line)-1] == '\t') {
			ck(false, "formatted source has no trailing whitespace")
			ok = false
			break
		}
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "gen.go", formatted, parser.ParseComments|parser.AllErrors)
	if err != nil {
		ck(false, "go/parser accepts generated source")
		return nil, false
	}
	if file.Name.Name != "main" {
		ck(false, "package main")
		ok = false
	}
	// format.Node 打印 AST 必须与 gofmt 输出逐字节一致。
	var printed bytes.Buffer
	if err := format.Node(&printed, fset, file); err != nil {
		ck(false, "format.Node")
		ok = false
	} else if !bytes.Equal(printed.Bytes(), formatted) {
		ck(false, "format.Node equals gofmt")
		ok = false
	}

	// 顶层 directive 必须保留在首个注释组。
	directive := false
	if len(file.Comments) > 0 {
		for _, c := range file.Comments[0].List {
			if strings.Contains(c.Text, "go:generate go run ./gen") {
				directive = true
			}
		}
	}
	if !directive {
		ck(false, "go:generate directive preserved")
		ok = false
	}

	pg := &parsedGen{src: formatted, fset: fset, file: file}
	typeIdx := 0
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			if d.Tok != token.TYPE {
				continue
			}
			if typeIdx >= len(cfg) {
				ck(false, "unexpected extra type decl")
				ok = false
				continue
			}
			want := cfg[typeIdx]
			if len(d.Specs) != 1 {
				ck(false, "one type spec per decl")
				ok = false
			}
			ts, isType := d.Specs[0].(*ast.TypeSpec)
			if !isType || ts.Name.Name != want.Name {
				ck(false, "generated type name")
				ok = false
				continue
			}
			st, isStruct := ts.Type.(*ast.StructType)
			if !isStruct {
				ck(false, "generated type is struct")
				ok = false
				continue
			}
			nf := len(st.Fields.List)
			if nf != len(want.Fields) {
				ck(false, "generated struct field count")
				ok = false
			}
			for j, f := range st.Fields.List {
				if j >= len(want.Fields) {
					break
				}
				if len(f.Names) != 1 || f.Names[0].Name != want.Fields[j].Name {
					ck(false, "generated field name")
					ok = false
				}
				if f.Tag == nil || !strings.Contains(f.Tag.Value, "json:\""+want.Fields[j].JSON+"\"") {
					ck(false, "generated struct tag")
					ok = false
				}
			}
			if d.Doc == nil || !strings.Contains(d.Doc.Text(), "is generated type number") {
				ck(false, "type doc comment preserved")
				ok = false
			}
			pg.fieldCnt = append(pg.fieldCnt, nf)
			pg.typeCnt++
			typeIdx++
		case *ast.FuncDecl:
			if typeIdx == 0 || typeIdx > len(cfg) {
				ck(false, "method outside generated types")
				ok = false
				continue
			}
			want := cfg[typeIdx-1]
			if d.Name.Name != "GetWeight" || d.Recv == nil || len(d.Recv.List) != 1 {
				ck(false, "generated method signature")
				ok = false
				continue
			}
			star, isStar := d.Recv.List[0].Type.(*ast.StarExpr)
			if !isStar {
				ck(false, "generated method receiver is pointer")
				ok = false
				continue
			}
			ident, isIdent := star.X.(*ast.Ident)
			if !isIdent || ident.Name != want.Name {
				ck(false, "generated method receiver type")
				ok = false
				continue
			}
			if d.Doc == nil || !strings.Contains(d.Doc.Text(), "GetWeight returns") {
				ck(false, "method doc comment preserved")
				ok = false
			}
			// 方法体里的返回值必须是配置中的 weight 常量。
			found := false
			ast.Inspect(d.Body, func(n ast.Node) bool {
				if lit, isLit := n.(*ast.BasicLit); isLit && lit.Kind == token.INT {
					if v, err := strconv.Atoi(lit.Value); err == nil && v == want.Weight {
						found = true
					}
				}
				return true
			})
			if !found {
				ck(false, "generated weight literal")
				ok = false
			}
			pg.funcCnt++
		}
	}
	if pg.typeCnt != len(cfg) {
		ck(false, "generated type count")
		ok = false
	}
	if pg.funcCnt != len(cfg) {
		ck(false, "generated method count")
		ok = false
	}
	return pg, ok
}

func main() {
	curSeed = 1
	if s := os.Getenv("UAF_SEED"); s != "" {
		if v, err := strconv.ParseInt(s, 10, 64); err == nil {
			curSeed = v
		}
	}

	// 1. 固定配置：确定性渲染 + 完整 AST 校验。
	cfg := makeConfig(rand.New(rand.NewSource(7)), 12)
	src1, err := render(cfg)
	ck(err == nil, "template render")
	src2, err := render(cfg)
	ck(err == nil && bytes.Equal(src1, src2), "template render deterministic")
	pg, ok := parseCheck(src1, cfg)
	ck(ok, "fixed generated source passes format/parser checks")
	ck(pg != nil && pg.typeCnt == 12 && pg.funcCnt == 12, "fixed AST counts")
	if pg != nil {
		retained := pg.src
		gcSink = append(gcSink, retained)
		gcStress()
		ck(bytes.Equal(pg.src, retained), "formatted source survives GC")
		// GC 后重新遍历 AST，字段数与类型数不变。
		types := 0
		fields := 0
		ast.Inspect(pg.file, func(n ast.Node) bool {
			if ts, isType := n.(*ast.TypeSpec); isType {
				if st, isStruct := ts.Type.(*ast.StructType); isStruct {
					types++
					fields += len(st.Fields.List)
				}
			}
			return true
		})
		wantFields := 0
		for _, t := range cfg {
			wantFields += len(t.Fields)
		}
		ck(types == 12 && fields == wantFields, "AST remains valid after GC")
	}

	// 2. 负例：语法错误必须被 go/format 与 go/parser 拒绝。
	bad := []byte("package main\n\nfunc broken( {\n")
	if _, err := format.Source(bad); err == nil {
		ck(false, "format.Source rejects syntax error")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "bad.go", bad, parser.AllErrors); err == nil {
		ck(false, "parser rejects syntax error")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "bad.go", "type X int\n", parser.AllErrors); err == nil {
		ck(false, "parser rejects missing package clause")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "bad.go", "package main\n\ntype X int\n", parser.ParseComments); err != nil {
		ck(false, "parser accepts minimal valid source")
	}

	// 3. 未格式化输入：gofmt 归一化后两路输出一致。
	messy, err := render(cfg)
	ck(err == nil, "messy render")
	messy = bytes.ReplaceAll(messy, []byte("\n\t"), []byte("\n\t\t"))
	mf, err := format.Source(messy)
	clean, err2 := format.Source(src1)
	ck(err == nil && err2 == nil && bytes.Equal(mf, clean), "gofmt normalizes whitespace deterministically")

	// 4. UAF_SEED 派生配置：不同规模全部通过 parser/format；GC 后复核。
	r := rand.New(rand.NewSource(curSeed))
	type held struct {
		src  []byte
		file *ast.File
		fset *token.FileSet
		cfg  []genType
	}
	var keep []held
	for round := 0; round < 4; round++ {
		n := 6 + r.Intn(24)
		c := makeConfig(r, n)
		s, err := render(c)
		ckSeed(err == nil, "random template render")
		if err != nil {
			continue
		}
		s1, _ := render(c)
		ckSeed(bytes.Equal(s, s1), "random render deterministic")
		p, ok := parseCheck(s, c)
		ckSeed(ok && p != nil, "random generated source passes checks")
		if p == nil {
			continue
		}
		ckSeed(p.typeCnt == n && p.funcCnt == n, "random AST counts")
		keep = append(keep, held{src: p.src, file: p.file, fset: p.fset, cfg: c})
		if round%2 == 0 {
			gcStress()
		}
	}
	runtime.GC()
	for i := range keep {
		h := &keep[i]
		types := 0
		for _, decl := range h.file.Decls {
			if gd, isGen := decl.(*ast.GenDecl); isGen && gd.Tok == token.TYPE {
				types++
			}
		}
		ckSeed(types == len(h.cfg), fmt.Sprintf("retained AST %d after GC", i))
		ckSeed(len(h.src) > 0 && h.src[len(h.src)-1] == '\n', "retained source intact")
	}
	gcSink = append(gcSink, keep[0].src)

	finish("l10_template_format_ast")
}
