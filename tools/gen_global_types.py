#!/usr/bin/env python3
"""Generate stress/y08_global_gcprog_storm/globals_gen.go.

36 giant global array declarations for the y08 global-gcprog scenario.
Element layout per type index k: r groups of [g]*node + [d]uint64
(pointer groups interleaved with long non-pointer runs). Sparse layouts
(k even: large pad runs, smaller arrays) push the runtime toward the gcprog
encode/decode path (B14/B15, issue1002 shape); dense layouts (k odd: huge
arrays, tiny pads) exercise the raw pointer-bitmap path.

Deterministic by construction: every layout parameter is a pure function of
the index — regeneration is byte-identical (sha-stable), no randomness, no
timestamps. Regenerate with:

    python3 tools/gen_global_types.py

The script refuses to emit output that drifts outside the y08 budget
(<= 256 MiB total declared bytes, >= 1,000,000 total pointer bits).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys

TYPE_COUNT = 36
MAX_TOTAL_BYTES = 256 << 20  # 256 MiB
MIN_TOTAL_PTRBITS = 1_000_000

HEADER = """// Code generated by tools/gen_global_types.py; DO NOT EDIT.
// y08 global-gcprog fixture: {count} giant global arrays with mixed
// pointer-group / non-pointer-run element layouts. Sparse layouts (k even:
// large pad runs, smaller arrays) stress the gcprog encode/decode path
// (B14/B15, issue1002 shape); dense layouts (k odd: huge arrays, tiny pads)
// exercise the raw pointer-bitmap path. Every layout parameter is a pure
// function of the type index, so regeneration is byte-identical.
//
// Regenerate with:
//
//\tpython3 tools/gen_global_types.py

package main

import (
\t"reflect"
\t"unsafe"
)

// genMeta describes one generated global: an array of r alternating
// pointer-group / pad-run blocks (last block is a pad run), plus the exact
// size/ptrdata derived from the layout (checked against reflect at runtime).
type genMeta struct {
\tname    string
\tg, d, r int // element layout: r groups of [g]*node + [d]uint64
\tn       int // array length
\tsize    uintptr
\tptrdata uintptr
\tptrbits int
}
"""


def params(k: int) -> tuple[int, int, int, int]:
    if k % 2 == 0:  # sparse: 大 pad run → gcprog 压缩形态
        g = 2 + k % 9          # 2..10
        d = 32 + (k * 61) % 224  # 32..255 words (256..2040 B)
        r = 2 + k % 4          # 2..5
        n = 64 + 64 * (k % 8)  # 64..448
    else:  # dense: 大数组、小 pad → 原始位图形态
        g = 4 + k % 12         # 4..15
        d = 4 + (k * 13) % 12  # 4..15 words
        r = 2 + k % 3          # 2..4
        n = 512 + 512 * (k % 8)  # 1024..4096
    return g, d, r, n


def meta(k: int) -> tuple[int, int, int, int, int, int, int]:
    g, d, r, n = params(k)
    elem_size = r * (g + d) * 8
    elem_ptrdata = elem_size - d * 8  # 最后一组以 pad 结尾
    size = n * elem_size
    ptrdata = (n - 1) * elem_size + elem_ptrdata
    ptrbits = n * r * g
    return g, d, r, n, size, ptrdata, ptrbits


def type_block(k: int) -> str:
    g, d, r, _n, _s, _p, _b = meta(k)
    lines = [f"type gt{k} struct {{"]
    for i in range(r):
        lines.append(f"\tP{i} [{g}]*node")
        lines.append(f"\tD{i} [{d}]uint64")
    lines.append("}")
    lines.append("")
    lines.append(f"var g{k} [{_n}]gt{k}")
    return "\n".join(lines)


def build() -> str:
    parts = [HEADER.replace("{count}", str(TYPE_COUNT))]
    parts.extend(type_block(k) for k in range(TYPE_COUNT))

    entries = []
    for k in range(TYPE_COUNT):
        g, d, r, n, size, ptrdata, ptrbits = meta(k)
        entries.append(
            f'\t{{name: "g{k}", g: {g}, d: {d}, r: {r}, n: {n}, '
            f"size: {size}, ptrdata: {ptrdata}, ptrbits: {ptrbits}}}"
        )
    parts.append("var genTable = []genMeta{\n" + ",\n".join(entries) + ",\n}")

    parts.append(
        "func genTypeList() []reflect.Type {\n\treturn []reflect.Type{\n"
        + "".join(f"\t\treflect.TypeOf(g{k}),\n" for k in range(TYPE_COUNT))
        + "\t}\n}"
    )
    parts.append(
        "func genBasePtrs() []unsafe.Pointer {\n\treturn []unsafe.Pointer{\n"
        + "".join(f"\t\tunsafe.Pointer(&g{k}),\n" for k in range(TYPE_COUNT))
        + "\t}\n}"
    )
    return "\n\n".join(parts) + "\n"


def gofmt(path: str) -> None:
    tool = shutil.which("gofmt")
    if tool is None:
        try:
            goroot = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
        except (OSError, subprocess.CalledProcessError):
            goroot = ""
        candidate = os.path.join(goroot, "bin", "gofmt") if goroot else ""
        tool = candidate if candidate and os.path.exists(candidate) else None
    if tool is None:
        print("warning: gofmt not found; output left unformatted", file=sys.stderr)
        return
    subprocess.run([tool, "-w", path], check=True)


def main() -> int:
    total_bytes = 0
    total_ptrbits = 0
    for k in range(TYPE_COUNT):
        _g, _d, _r, _n, size, _p, ptrbits = meta(k)
        total_bytes += size
        total_ptrbits += ptrbits
    if total_bytes > MAX_TOTAL_BYTES:
        print(
            f"error: total bytes {total_bytes} exceeds budget {MAX_TOTAL_BYTES}",
            file=sys.stderr,
        )
        return 1
    if total_ptrbits < MIN_TOTAL_PTRBITS:
        print(
            f"error: total ptrbits {total_ptrbits} below minimum {MIN_TOTAL_PTRBITS}",
            file=sys.stderr,
        )
        return 1
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "stress", "y08_global_gcprog_storm", "globals_gen.go")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(build())
    gofmt(out)
    with open(out, "r", encoding="utf-8") as f:
        lines = sum(1 for _ in f)
    print(
        f"generated {out} ({lines} lines, {TYPE_COUNT} types, "
        f"total={total_bytes / 1e6:.1f}MB, ptrbits={total_ptrbits})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
