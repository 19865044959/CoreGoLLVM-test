#!/usr/bin/env python3
"""Generate stress/s05_generated_code_soak/generated.go.

The output mimics protobuf/ORM generated code: 64 record types with
getters/setters, a shared pointer payload type, deep-copy functions, a
1024-branch dispatch switch and enum/description tables.

Deterministic by construction: fixed type count, fixed constants, no
randomness. Regenerate with:

    python3 tools/gen_stress_code.py

The script formats the output with gofmt when available.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from string import Template

RECORD_COUNT = 64
DISPATCH_CASES = 1024

HEADER = """// Code generated by tools/gen_stress_code.py; DO NOT EDIT.
// s05 generated-code soak fixture: 64 protobuf/ORM-shaped record types,
// accessors, deep copies, enum/description tables and a 1024-branch dispatch.

package main

import "strconv"
"""

PAYLOAD = """// Payload is the shared pointer field used by every generated record.
type Payload struct {
	ID       int64      `json:"id"`
	Key      string     `json:"key"`
	Value    int64      `json:"value"`
	Weight   int32      `json:"weight"`
	Data     []byte     `json:"data"`
	Children []*Payload `json:"children"`
}

func (p *Payload) GetID() int64 {
	if p == nil {
		return 0
	}
	return p.ID
}

func (p *Payload) GetValue() int64 {
	if p == nil {
		return 0
	}
	return p.Value
}

func (p *Payload) Checksum() int64 {
	if p == nil {
		return 0
	}
	h := p.ID*0x9E3779B1 ^ p.Value*0x85EBCA6B ^ int64(p.Weight)
	h = checksumString(h, p.Key)
	h = h*137 + int64(len(p.Data))
	for _, b := range p.Data {
		h = h*139 + int64(b)
	}
	h = h*149 + int64(len(p.Children))
	for _, c := range p.Children {
		h = h*7 + c.Checksum()
	}
	return h
}

func (p *Payload) DeepCopy() *Payload {
	if p == nil {
		return nil
	}
	out := *p
	if p.Data != nil {
		out.Data = make([]byte, len(p.Data))
		copy(out.Data, p.Data)
	}
	out.Children = make([]*Payload, len(p.Children))
	for i := 0; i < len(p.Children); i++ {
		out.Children[i] = p.Children[i].DeepCopy()
	}
	return &out
}

// NewPayload builds the deterministic payload content for a record seed.
func NewPayload(seed int64, idx int64) *Payload {
	return &Payload{
		ID:     seed*100 + idx + 1,
		Key:    "payload/" + strconv.FormatInt(idx, 10),
		Value:  seed*17 + idx*13,
		Weight: int32(idx*31 + 7),
		Data:   []byte{byte(seed), byte(seed >> 8), byte(idx), 0x5A},
		Children: []*Payload{
			{
				ID:     seed*100 + idx + 1001,
				Key:    "child/" + strconv.FormatInt(idx, 10),
				Value:  seed + idx*3 + 1,
				Weight: int32(idx + 3),
				Data:   []byte{byte(seed >> 16), byte(idx), 0xC3},
			},
		},
	}
}

func checksumString(h int64, s string) int64 {
	for i := 0; i < len(s); i++ {
		h = h*131 + int64(s[i])
	}
	return h
}

func checksumPayloads(h int64, ps []*Payload) int64 {
	h = h*149 + int64(len(ps))
	for _, p := range ps {
		h = h*7 + p.Checksum()
	}
	return h
}"""

INTERFACE = """// Record is the interface every generated record implements.
type Record interface {
	Kind() RecordKind
	GetID() int64
	GetName() string
	SetID(v int64)
	SetName(v string)
	Checksum() int64
	DeepCopyRecord() Record
	Payloads() []*Payload
	LeaderPayload() *Payload
	TagValues() []string
	MutatePayload(delta int64)
	MutateTag(v string)
}"""

