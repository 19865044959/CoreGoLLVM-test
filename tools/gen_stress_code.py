def record_block(i: int) -> str:
    n = "%03d" % i
    # Keep the emitted block dense so the fixture stays in the 5k-10k line range.
    return RECORD_TMPL.substitute(idx=i, n=n, Kind="KindRecord" + n).replace("\n\n", "\n")


def enum_block() -> str:
    lines = ["// RecordKind enumerates generated record types.", "type RecordKind int32", "", "const ("]
    for i in range(RECORD_COUNT):
        n = "%03d" % i
        if i == 0:
            lines.append("\tKindRecord%s RecordKind = iota" % n)
        else:
            lines.append("\tKindRecord%s" % n)
    lines.append(")")
    lines.append("")
    lines.append("// RecordKindCount is the number of generated record types.")
    lines.append("const RecordKindCount = %d" % RECORD_COUNT)
    lines.append("")
    lines.append("var recordKindNames = [RecordKindCount]string{")
    for i in range(RECORD_COUNT):
        lines.append('\t"Rec%03d",' % i)
    lines.append("}")
    lines.append("")
    lines.append("var recordKindDescriptions = [RecordKindCount]string{")
    for i in range(RECORD_COUNT):
        lines.append('\t"generated record %03d: protobuf/ORM shaped fixture",' % i)
    lines.append("}")
    lines.append("")
    lines.append("func (k RecordKind) String() string {")
    lines.append("\tif k < 0 || int(k) >= RecordKindCount {")
    lines.append('\t\treturn "RecordKind(invalid)"')
    lines.append("\t}")
    lines.append("\treturn recordKindNames[k]")
    lines.append("}")
    lines.append("")
    lines.append("// KindName returns the stable name of a record kind.")
    lines.append("func KindName(k RecordKind) string {")
    lines.append("\treturn k.String()")
    lines.append("}")
    lines.append("")
    lines.append("// KindDescription returns the description table entry for a record kind.")
    lines.append("func KindDescription(k RecordKind) string {")
    lines.append("\tif k < 0 || int(k) >= RecordKindCount {")
    lines.append('\t\treturn "invalid record kind"')
    lines.append("\t}")
    lines.append("\treturn recordKindDescriptions[k]")
    lines.append("}")
    return "\n".join(lines)


def factory_block() -> str:
    lines = ["var recordConstructors = [...]func(int64) Record{"]
    for i in range(RECORD_COUNT):
        lines.append("\tfunc(seed int64) Record { return newRec%03d(seed) }," % i)
    lines.append("}")
    lines.append("")
    lines.append("var recordEmpties = [...]func() Record{")
    for i in range(RECORD_COUNT):
        lines.append("\tfunc() Record { return &Rec%03d{} }," % i)
    lines.append("}")
    lines.append("")
    lines.append("// NewRecord builds a populated record of the requested kind.")
    lines.append("func NewRecord(kind RecordKind, seed int64) Record {")
    lines.append("\tif kind < 0 || int(kind) >= RecordKindCount {")
    lines.append("\t\treturn nil")
    lines.append("\t}")
    lines.append("\treturn recordConstructors[kind](seed)")
    lines.append("}")
    lines.append("")
    lines.append("// NewEmptyRecord builds a zero-value record of the requested kind.")
    lines.append("func NewEmptyRecord(kind RecordKind) Record {")
    lines.append("\tif kind < 0 || int(kind) >= RecordKindCount {")
    lines.append("\t\treturn nil")
    lines.append("\t}")
    lines.append("\treturn recordEmpties[kind]()")
    lines.append("}")
    return "\n".join(lines)


def dispatch_block() -> str:
    lines = [
        "// Dispatch exercises a generated 1024-branch switch over record methods.",
        "func Dispatch(op int32, r Record) int64 {",
        "\tif r == nil {",
        "\t\treturn -1",
        "\t}",
        "\tswitch op & 1023 {",
    ]
    primes = (3, 5, 7, 11)
    for i in range(DISPATCH_CASES):
        p = primes[i % 4]
        lines.append("\tcase %d:" % i)
        if i % 4 == 0:
            lines.append("\t\treturn r.Checksum()*%d + r.GetID() + %d" % (p, i))
        elif i % 4 == 1:
            lines.append("\t\treturn r.Checksum() ^ (r.GetID()+%d)*%d" % (i, p))
        elif i % 4 == 2:
            lines.append("\t\treturn (r.Checksum() + int64(len(r.GetName())))*%d - %d" % (p, i))
        else:
            lines.append("\t\treturn r.Checksum()/2 + r.GetID()*%d + %d" % (p, i))
    lines.append("\t}")
    lines.append("\treturn 0")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    parts = [HEADER, PAYLOAD, INTERFACE]
    parts.append(enum_block())
    parts.extend(record_block(i) for i in range(RECORD_COUNT))
    parts.append(factory_block())
    parts.append(dispatch_block())
    return "\n\n".join(parts) + "\n"


def gofmt(path: str) -> None:
    tool = shutil.which("gofmt")
    if tool is None:
        try:
            goroot = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
        except (OSError, subprocess.CalledProcessError):
            goroot = ""
        candidate = os.path.join(goroot, "bin", "gofmt") if goroot else ""
        tool = candidate if candidate and os.path.exists(candidate) else None
    if tool is None:
        print("warning: gofmt not found; output left unformatted", file=sys.stderr)
        return
    subprocess.run([tool, "-w", path], check=True)


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "stress", "s05_generated_code_soak", "generated.go")
    source = generate()
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    gofmt(out)
    with open(out, "r", encoding="utf-8") as f:
        lines = sum(1 for _ in f)
    print("generated %s (%d lines, %d record types, %d dispatch cases)" % (out, lines, RECORD_COUNT, DISPATCH_CASES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
