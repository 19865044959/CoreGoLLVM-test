// N08: parser/typecheck/format 长跑。
// 每个 worker 在每一轮用固定模板 + seed 派生参数生成约 2000 行合法 Go 源
// （const/泛型 struct/接口/方法/函数/闭包/递归指针字段），随后：
// go/parser.ParseFile → runtime.GC → go/types.Check（配 basic types/Info）→ printer.Fprint；
// 保留 AST/typeinfo 快照跨 GC 校验，AST 节点计数与 checksum、类型数、格式化输出跨轮稳定。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"go/types"
	"hash/fnv"
	"os"
	"reflect"
	"runtime"
	"runtime/debug"
	"strconv"
	"strings"
	"sync"
	"sync/atomic"
	"time"
)

const (
	nTypes   = 32
	nFuncs   = 24
	nConsts  = 120
	ringSize = 2
)

var (
	beats        int64
	parses       int64
	typechecks   int64
	formatBytes  int64
	astNodeTotal int64
)

func failf(format string, args ...interface{}) {
	fmt.Printf("FAIL: "+format+"\n", args...)
	buf := make([]byte, 1<<20)
	n := runtime.Stack(buf, true)
	fmt.Fprintf(os.Stderr, "%s", buf[:n])
	os.Exit(1)
}

func envInt(key string, def, min, max int) int {
	s := os.Getenv(key)
	if s == "" {
		return def
	}
	v, err := strconv.Atoi(s)
	if err != nil || v < min {
		return def
	}
	if v > max {
		return max
	}
	return v
}

func envSeed(def uint64) uint64 {
	s := os.Getenv("UAF_SEED")
	if s == "" {
		return def
	}
	v, err := strconv.ParseUint(s, 10, 64)
	if err != nil || v == 0 {
		return def
	}
	return v
}

func expectedScopeLen() int {
	// Pair + Summer + T* + 变量 S* + MakePair + F* + 常量 C*
	return (nTypes + 2) + nTypes + (nFuncs + 1) + nConsts
}

// genSource 生成一个自包含、无 import、类型正确的 Go 包。
// 同一 seed 输出逐字节稳定；不同 seed 只改常量/初值/数字参数。
func genSource(seed uint64) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by n08 stress seed=%d; DO NOT EDIT.\n", seed)
	b.WriteString("package gen\n\n")
	b.WriteString("type Pair[T any] struct {\n\tA T\n\tB T\n}\n\n")
	b.WriteString("func MakePair[T any](a, b T) Pair[T] {\n\treturn Pair[T]{A: a, B: b}\n}\n\n")
	b.WriteString("type Summer interface {\n\tSum() int\n\tDescribe() string\n}\n\n")

	b.WriteString("const (\n")
	for i := 0; i < nConsts; i++ {
		fmt.Fprintf(&b, "\tC%03d = %d\n", i, i*3+int(seed%7))
	}
	b.WriteString(")\n\n")

	for i := 0; i < nTypes; i++ {
		next := (i + 1) % nTypes
		fmt.Fprintf(&b, "type T%03d struct {\n", i)
		b.WriteString("\tID int\n\tName string\n")
		fmt.Fprintf(&b, "\tNext *T%03d\n", i)
		fmt.Fprintf(&b, "\tPeer *T%03d\n", next)
		fmt.Fprintf(&b, "\tKids []*T%03d\n", i)
		b.WriteString("\tTable map[string]int\n\tPair Pair[int]\n\tFlag bool\n}\n\n")

		fmt.Fprintf(&b, "func (t *T%03d) Sum() int {\n", i)
		b.WriteString("\tif t == nil {\n\t\treturn 0\n\t}\n")
		b.WriteString("\ts := t.ID\n")
		fmt.Fprintf(&b, "\tfor i := 0; i < len(t.Kids); i++ {\n\t\tif t.Kids[i] != nil {\n\t\t\ts += t.Kids[i].ID * %d\n\t\t}\n\t}\n", 1+i%5)
		b.WriteString("\tfor k, v := range t.Table {\n\t\ts += len(k)*v + 1\n\t}\n")
		b.WriteString("\tif t.Next != nil {\n\t\ts += t.Next.ID % 7\n\t}\n")
		b.WriteString("\tif t.Peer != nil {\n\t\ts += t.Peer.ID % 11\n\t}\n")
		b.WriteString("\tif t.Pair.A > 0 {\n\t\ts += t.Pair.A\n\t}\n")
		b.WriteString("\tif t.Flag {\n\t\ts += 1\n\t}\n")
		fmt.Fprintf(&b, "\treturn s + C%03d\n}\n\n", i)

		fmt.Fprintf(&b, "func (t *T%03d) Describe() string {\n", i)
		b.WriteString("\tif t == nil {\n\t\treturn \"nil\"\n\t}\n\treturn t.Name\n}\n\n")
	}

	for i := 0; i < nTypes; i++ {
		fmt.Fprintf(&b, "var S%03d Summer = &T%03d{ID: %d, Name: \"t%03d\", Table: map[string]int{\"k\": %d}, Pair: MakePair[int](%d, %d), Flag: %v}\n\n",
			i, i, i, i, i%7, i, i+1, i%2 == 0)
	}

	for f := 0; f < nFuncs; f++ {
		fmt.Fprintf(&b, "func F%03d(a int, b string) (int, string) {\n", f)
		if f%3 == 0 {
			b.WriteString("\ttotal := 0\n")
			b.WriteString("\tadd := func(x int) int {\n\t\ttotal += x\n\t\treturn total\n\t}\n")
			b.WriteString("\tdefer func() {\n\t\tif total < 0 {\n\t\t\ttotal = -total\n\t\t}\n\t}()\n")
			fmt.Fprintf(&b, "\tfor i := 0; i < %d; i++ {\n\t\ttotal += add(i) %% 13\n\t}\n", 5+f%6)
			b.WriteString("\tp := MakePair[int](total, a)\n")
			fmt.Fprintf(&b, "\tif b == \"\" {\n\t\treturn p.A + p.B, \"empty%03d\"\n\t}\n", f)
			b.WriteString("\treturn p.A + p.B + len(b), b\n}\n\n")
			continue
		}
		fmt.Fprintf(&b, "\ttotal := a + %d\n", f%9)
		fmt.Fprintf(&b, "\tfor i := 0; i < %d; i++ {\n", 6+f%5)
		b.WriteString("\t\tswitch (a + i) % 5 {\n")
		b.WriteString("\t\tcase 0:\n\t\t\ttotal += i * 3\n")
		b.WriteString("\t\tcase 1:\n\t\t\ttotal -= i\n")
		b.WriteString("\t\tcase 2:\n\t\t\tif b != \"\" {\n\t\t\t\ttotal += len(b)\n\t\t\t}\n")
		b.WriteString("\t\tdefault:\n\t\t\ttotal ^= i\n")
		b.WriteString("\t\t}\n\t}\n")
		fmt.Fprintf(&b, "\tt := &T%03d{ID: total, Name: b, Table: map[string]int{\"a\": total}, Pair: MakePair[int](total, a)}\n", f%nTypes)
		b.WriteString("\ttotal += t.Sum()\n\tif total < 0 {\n\t\ttotal = -total\n\t}\n")
		fmt.Fprintf(&b, "\treturn total + %d, b + \"f%03d\"\n}\n\n", f%17, f)
	}
	return b.String()
}

// astStats 统计 AST 节点数并计算位置/类型派生的 FNV checksum（同一 fset 下稳定）。
func astStats(file *ast.File, fset *token.FileSet) (int, uint64) {
	tf := fset.File(file.Pos())
	if tf == nil {
		failf("phase=ast: file not in FileSet")
	}
	base := tf.Base()
	var h uint64 = 1469598103934665603
	nodes := 0
	ast.Inspect(file, func(n ast.Node) bool {
		if n == nil {
			return true
		}
		nodes++
		t := reflect.TypeOf(n).String()
		for i := 0; i < len(t); i++ {
			h ^= uint64(t[i])
			h *= 1099511628211
		}
		h ^= uint64(n.Pos() - token.Pos(base))
		h *= 1099511628211
		return true
	})
	return nodes, h
}

func fnvBytes(b []byte) uint64 {
	h := fnv.New64a()
	_, _ = h.Write(b)
	return h.Sum64()
}

type snapshot struct {
	file        *ast.File
	fset        *token.FileSet
	info        *types.Info
	pkg         *types.Package
	astNodes    int
	astSum      uint64
	fmtLen      int
	fmtSum      uint64
	typeEntries int
	useEntries  int
	scopeLen    int
	typeNames   int
}

type expect struct {
	srcLen, astNodes int
	astSum, fmtSum   uint64
	fmtLen           int
	scopeLen         int
	typeNames        int
	typeEntries      int
	useEntries       int
	instances        int
}

type worker struct {
	id      int64
	seed    uint64
	rounds  int64
	haveExp bool
	exp     expect
	ring    []*snapshot
}

func verifySnapshot(s *snapshot, phase string, id int64) {
	nodes, sum := astStats(s.file, s.fset)
	if nodes != s.astNodes || sum != s.astSum {
		failf("phase=%s worker=%d: AST changed after GC (nodes=%d→%d sum=%x→%x)", phase, id, s.astNodes, nodes, s.astSum, sum)
	}
	if len(s.info.Types) != s.typeEntries || len(s.info.Uses) != s.useEntries {
		failf("phase=%s worker=%d: type info shrunk after GC (types=%d→%d uses=%d→%d)",
			phase, id, s.typeEntries, len(s.info.Types), s.useEntries, len(s.info.Uses))
	}
	if s.pkg.Scope().Len() != s.scopeLen {
		failf("phase=%s worker=%d: package scope len=%d→%d", phase, id, s.scopeLen, s.pkg.Scope().Len())
	}
	obj := s.pkg.Scope().Lookup("T000")
	if obj == nil {
		failf("phase=%s worker=%d: T000 vanished from scope", phase, id)
	}
	named, ok := obj.Type().(*types.Named)
	if !ok {
		failf("phase=%s worker=%d: T000 is not a named type (%T)", phase, id, obj.Type())
	}
	if types.NewMethodSet(types.NewPointer(named)).Len() < 2 {
		failf("phase=%s worker=%d: T000 method set lost after GC", phase, id)
	}
	var fbuf bytes.Buffer
	if err := printer.Fprint(&fbuf, s.fset, s.file); err != nil {
		failf("phase=%s worker=%d: printer after GC: %v", phase, id, err)
	}
	if fbuf.Len() != s.fmtLen || fnvBytes(fbuf.Bytes()) != s.fmtSum {
		failf("phase=%s worker=%d: formatted output changed after GC (len=%d→%d)", phase, id, s.fmtLen, fbuf.Len())
	}
}

func (w *worker) round(r int64) {
	src := genSource(w.seed)
	if lines := strings.Count(src, "\n"); lines < 1500 {
		failf("phase=gen worker=%d round=%d seed=%d: generated only %d lines", w.id, r, w.seed, lines)
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "gen.go", src, parser.ParseComments|parser.AllErrors)
	if err != nil {
		failf("phase=parse worker=%d round=%d seed=%d: %v", w.id, r, w.seed, err)
	}
	atomic.AddInt64(&parses, 1)
	nodes, sum := astStats(file, fset)
	if nodes < 4000 {
		failf("phase=parse worker=%d round=%d seed=%d: AST node count=%d", w.id, r, w.seed, nodes)
	}

	runtime.GC() // AST 跨 GC 后继续 typecheck

	info := &types.Info{
		Types:      make(map[ast.Expr]types.TypeAndValue),
		Defs:       make(map[*ast.Ident]types.Object),
		Uses:       make(map[*ast.Ident]types.Object),
		Implicits:  make(map[ast.Node]types.Object),
		Scopes:     make(map[ast.Node]*types.Scope),
		Selections: make(map[*ast.SelectorExpr]*types.Selection),
		Instances:  make(map[*ast.Ident]types.Instance),
	}
	var terr []string
	conf := types.Config{Error: func(err error) {
		if len(terr) < 8 {
			terr = append(terr, err.Error())
		}
	}}
	pkg, err := conf.Check("stress/gen", fset, []*ast.File{file}, info)
	if err != nil || len(terr) != 0 {
		failf("phase=typecheck worker=%d round=%d seed=%d: err=%v first=%v", w.id, r, w.seed, err, terr)
	}
	atomic.AddInt64(&typechecks, 1)

	scopeLen := pkg.Scope().Len()
	typeNames := 0
	for _, name := range pkg.Scope().Names() {
		if _, ok := pkg.Scope().Lookup(name).(*types.TypeName); ok {
			typeNames++
		}
	}
	if typeNames != nTypes+2 {
		failf("phase=typecheck worker=%d round=%d: type count=%d want=%d", w.id, r, typeNames, nTypes+2)
	}
	if want := expectedScopeLen(); scopeLen != want {
		failf("phase=typecheck worker=%d round=%d: scope len=%d want=%d", w.id, r, scopeLen, want)
	}
	if len(info.Instances) == 0 || len(info.Uses) == 0 || len(info.Types) == 0 {
		failf("phase=typecheck worker=%d round=%d: empty type info (inst=%d uses=%d types=%d)",
			w.id, r, len(info.Instances), len(info.Uses), len(info.Types))
	}

	var fbuf bytes.Buffer
	if err := printer.Fprint(&fbuf, fset, file); err != nil {
		failf("phase=format worker=%d round=%d: %v", w.id, r, err)
	}
	if fbuf.Len() < 1000 || !bytes.Contains(fbuf.Bytes(), []byte("package gen")) {
		failf("phase=format worker=%d round=%d: bad output len=%d", w.id, r, fbuf.Len())
	}
	fmtLen := fbuf.Len()
	fmtSum := fnvBytes(fbuf.Bytes())
	atomic.AddInt64(&formatBytes, int64(fmtLen))
	atomic.AddInt64(&astNodeTotal, int64(nodes))

	cur := expect{
		srcLen: len(src), astNodes: nodes, astSum: sum,
		fmtLen: fmtLen, fmtSum: fmtSum,
		scopeLen: scopeLen, typeNames: typeNames,
		typeEntries: len(info.Types), useEntries: len(info.Uses), instances: len(info.Instances),
	}
	if !w.haveExp {
		w.exp = cur
		w.haveExp = true
	} else if w.exp != cur {
		failf("phase=stability worker=%d round=%d seed=%d: cross-round invariants changed (ast %d→%d sum %x→%x fmt %x→%x)",
			w.id, r, w.seed, w.exp.astNodes, cur.astNodes, w.exp.astSum, cur.astSum, w.exp.fmtSum, cur.fmtSum)
	}

	runtime.GC() // 保留快照跨 GC 校验
	for _, s := range w.ring {
		verifySnapshot(s, "retained", w.id)
	}

	snap := &snapshot{
		file: file, fset: fset, info: info, pkg: pkg,
		astNodes: nodes, astSum: sum, fmtLen: fmtLen, fmtSum: fmtSum,
		typeEntries: len(info.Types), useEntries: len(info.Uses),
		scopeLen: scopeLen, typeNames: typeNames,
	}
	if len(w.ring) >= ringSize {
		w.ring[0] = nil
		w.ring = w.ring[1:]
	}
	w.ring = append(w.ring, snap)
	verifySnapshot(snap, "fresh", w.id)

	atomic.AddInt64(&beats, 1)
	w.rounds = r
}

func (w *worker) run(deadline time.Time, seconds int, fixed int64) {
	r := int64(0)
	for {
		if seconds > 0 {
			if time.Now().After(deadline) {
				break
			}
		} else if r >= fixed {
			break
		}
		w.round(r)
		r++
	}
	for _, s := range w.ring {
		verifySnapshot(s, "final", w.id)
	}
}

func watchdog(interval time.Duration, stop <-chan struct{}, wg *sync.WaitGroup) {
	defer wg.Done()
	last := atomic.LoadInt64(&beats)
	lastChange := time.Now()
	t := time.NewTicker(interval)
	defer t.Stop()
	for {
		select {
		case <-stop:
			return
		case <-t.C:
			cur := atomic.LoadInt64(&beats)
			if cur != last {
				last = cur
				lastChange = time.Now()
				continue
			}
			if time.Since(lastChange) > 6*interval {
				failf("watchdog stalled: no worker progress for %s (beats=%d)", time.Since(lastChange), cur)
			}
		}
	}
}

// 把 fatal/panic 的 crash 文本写到 runner 指定的文件（core 不可用的环境用）。
func setupCrashOutput() {
	p := os.Getenv("STRESS_CRASH_FILE")
	if p == "" {
		return
	}
	f, err := os.OpenFile(p, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return
	}
	_ = debug.SetCrashOutput(f, debug.CrashOptions{})
}

func main() {
	setupCrashOutput()
	seconds := envInt("STRESS_SECONDS", 60, 0, 86400)
	workers := envInt("STRESS_WORKERS", 2, 1, 8)
	hb := envInt("STRESS_HEARTBEAT", 5, 1, 60)
	seed := envSeed(1)
	fixed := int64(envInt("STRESS_FIXED_ROUNDS", 6, 1, 100000))

	fmt.Printf("scenario=n08 phase=preflight go=%s goos=%s goarch=%s gomaxprocs=%d seed=%d seconds=%d workers=%d heartbeat=%ds\n",
		runtime.Version(), runtime.GOOS, runtime.GOARCH, runtime.GOMAXPROCS(0), seed, seconds, workers, hb)

	startBase := runtime.NumGoroutine()
	deadline := time.Now().Add(time.Duration(seconds) * time.Second)
	stop := make(chan struct{})

	ws := make([]*worker, workers)
	var wg sync.WaitGroup
	for i := 0; i < workers; i++ {
		w := &worker{id: int64(i), seed: seed*1000 + uint64(i) + 1}
		ws[i] = w
		wg.Add(1)
		go func() {
			defer wg.Done()
			w.run(deadline, seconds, fixed)
		}()
	}
	var helpers sync.WaitGroup
	helpers.Add(1)
	go watchdog(time.Duration(hb)*time.Second, stop, &helpers)

	wg.Wait()
	close(stop)
	helpers.Wait()

	runtime.GC()
	final := runtime.NumGoroutine()
	if final > startBase+8 {
		failf("phase=quiesce: goroutine baseline exceeded: final=%d start=%d", final, startBase)
	}

	var m runtime.MemStats
	runtime.ReadMemStats(&m)
	fmt.Printf("metrics: rounds=%d beats=%d parses=%d typechecks=%d ast_nodes_last=%d ast_nodes_total=%d types=%d scope=%d instantiations=%d format_bytes=%d retained=%d goroutines_start=%d goroutines_final=%d heap_alloc=%d heap_objects=%d num_gc=%d\n",
		ws[0].rounds, atomic.LoadInt64(&beats), atomic.LoadInt64(&parses), atomic.LoadInt64(&typechecks),
		ws[0].exp.astNodes, atomic.LoadInt64(&astNodeTotal), ws[0].exp.typeNames, ws[0].exp.scopeLen,
		ws[0].exp.instances, atomic.LoadInt64(&formatBytes), len(ws[0].ring),
		startBase, final, m.HeapAlloc, m.HeapObjects, m.NumGC)
	fmt.Println("STRESS PASS n08_parser_typecheck")
}
